"""Gap report → plain text, for /report's `DOWNLOAD REPORT` button.

The button shipped as a dead control (comp 05 / DESIGN_SYSTEM §6 promise a
download, but there was no route behind it). `POST /api/report/export` renders
the analysis the client already holds — stateless like every other route — into
a document through `export.py`, so the file always matches the numbers on
screen.

Kept as plain text on purpose: the DOCX/PDF renderers lay text out line by
line, so no layout can drift from the data. New punctuation stays ASCII —
export.py's PDF path uses reportlab's Helvetica (Windows-1252), which carries
the copy deck's em dashes but not arrows or curly quotes.
"""

CATEGORY_LABELS = {
    "technical": "Technical",
    "tools": "Tools",
    "soft": "Soft Skills",
}

_ORDER = ("technical", "tools", "soft")


def _grouped(skills: list[dict]) -> list[tuple[str, list[dict]]]:
    """Skills by category in the fixed technical → tools → soft order, empty
    categories omitted (same rule as the results screen)."""
    groups: list[tuple[str, list[dict]]] = []
    for category in _ORDER:
        items = [item for item in skills if item.get("category") == category]
        if items:
            groups.append((CATEGORY_LABELS[category], items))
    return groups


def _mentions(count: int) -> str:
    return f"mentioned {count} time" + ("" if count == 1 else "s")


def render(analysis: dict) -> str:
    """Analysis payload → the report body as text lines."""
    lines: list[str] = []
    add = lines.append
    score = int(analysis.get("match_score") or 0)

    add("GAP ANALYSIS REPORT")
    add("GapAnalyzer")
    add("")
    add(f"ROLE: {analysis.get('job_title') or 'Not specified'}")
    add(f"COMPANY: {analysis.get('company') or 'Not specified'}")
    add(f"MATCH SCORE: {score}%")
    add("")

    add("CATEGORY BREAKDOWN")
    categories = analysis.get("categories") or {}
    for category in _ORDER:
        add(f"  {CATEGORY_LABELS[category]}: {int(categories.get(category, 0))}%")
    add("")

    matched = analysis.get("matched_skills") or []
    add(f"MATCHED SKILLS ({len(matched)})")
    if matched:
        for label, items in _grouped(matched):
            names = ", ".join(item["skill"] for item in items)
            add(f"  {label}")
            add(f"    {names}")
    else:
        add("  No keywords matched")
    add("")

    missing = analysis.get("missing_skills") or []
    add(f"MISSING SKILLS ({len(missing)})")
    if missing:
        for label, items in _grouped(missing):
            add(f"  {label}")
            for item in items:
                mentions = int(item.get("jd_mentions") or 0)
                add(f"    - {item['skill']} ({_mentions(mentions)})")
                why = (item.get("why") or "").strip()
                if why:
                    add(f"      {why}")
    else:
        add("  No missing skills - the resume covers every keyword in the posting")
    add("")

    recommendations = analysis.get("recommendations") or []
    if recommendations:
        add("RECOMMENDATIONS")
        for index, rec in enumerate(recommendations, start=1):
            label = CATEGORY_LABELS.get(rec.get("category"), "")
            add(f"  {index}. [{label}] {rec.get('message', '')}")
        add("")

    diff = analysis.get("diff_example") or {}
    original = (diff.get("original") or "").strip()
    suggested = (diff.get("suggested") or "").strip()
    if original and suggested:
        add("EXAMPLE DIFF")
        add("  ORIGINAL")
        add(f"    {original}")
        add("  SUGGESTED")
        add(f"    {suggested}")
        add("")

    add(
        "Generated by GapAnalyzer - every missing skill above was not found "
        "in the resume."
    )
    return "\n".join(lines)
